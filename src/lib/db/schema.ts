import { boolean, integer, numeric, pgTable, text, timestamp, uuid } from 'drizzle-orm/pg-core'

export const products = pgTable('products', {
  id: text('id').primaryKey(),
  name: text('name').notNull(),
  // 'Chinese Pokémon Products' | 'Acrylic Cases'
  category: text('category').notNull(),
  // Gem Series | CSV Series | Blind Box (under Chinese Pokémon Products)
  // ETB Case | Booster Box Case | SPC Box Case (under Acrylic Cases)
  subcategory: text('subcategory').notNull(),
  price: numeric('price', { precision: 10, scale: 2, mode: 'number' }).notNull(),
  compareAtPrice: numeric('compare_at_price', { precision: 10, scale: 2, mode: 'number' }),
  stock: integer('stock').notNull().default(0),
  squareVariationId: text('square_variation_id'),
  // GS1 GTIN-13 (UPC/EAN barcode) — same field name/format Square uses on
  // its own catalog items, kept here rather than read live from Square
  // since it's static (never changes with stock/price) and not every
  // product is necessarily linked to Square. Feeds a future Google
  // Merchant Center product feed; validated (13 digits + correct check
  // digit) in admin.ts, not at the DB level, since it's optional per
  // product (many won't have one yet).
  gtin: text('gtin'),
  // The manufacturer/IP brand shown to shoppers (e.g. "Pokémon") — not the
  // seller name, which Merchant Center already knows separately. Near-
  // constant across this catalog today, but a real column rather than a
  // hardcoded value in case a different licensed line is ever carried.
  brand: text('brand'),
  // Google's condition [condition] values: new | used | refurbished — this
  // catalog needs it because the same GTIN/product can legitimately be
  // sold both still-sealed ("new") and opened-by-us-to-reveal-contents
  // ("used"); Google's own definition of "new" requires unopened original
  // packaging, so an opened item must say "used" or the listing risks a
  // condition-mismatch flag against its own description.
  condition: text('condition'),
  // Google's google_product_category [google_product_category] — the
  // exact taxonomy string/ID from Merchant Center's own category picker,
  // e.g. "Arts & Entertainment > Hobbies & Creative Arts > Collectibles >
  // Collectible Trading Cards". Deliberately free text filled in by admin
  // per product/subcategory rather than a hardcoded per-subcategory
  // mapping in code — the exact taxonomy path needs to come from Google's
  // own current category list, not guessed.
  googleProductCategory: text('google_product_category'),
  // Per-unit weight in pounds — needed to get a real Shippo rate quote for
  // Alaska/Hawaii orders (see resolveHiAkShippingRate in server/shippo.ts).
  // Nullable/admin-filled like gtin/brand/etc; a product with no weight set
  // falls back to a conservative default in that lookup rather than
  // quoting nothing.
  weightLb: numeric('weight_lb', { precision: 6, scale: 3, mode: 'number' }),
  img: text('img'),
  // Tablet/mobile are optional — a viewport falls back to `img` (the
  // desktop/default version) when its size-specific version isn't set.
  // These are admin-supplied pre-sized files, not generated by the app.
  imgTablet: text('img_tablet'),
  imgMobile: text('img_mobile'),
  imgAlt: text('img_alt'),
  images: text('images').array().notNull().default([]),
  // Free-form collection labels (e.g. "Gem Series", "CSV Series") — see
  // ProductSubcategory in lib/products.ts for why these are tags rather
  // than a fixed subcategory.
  tags: text('tags').array().notNull().default([]),
  // Rank within the homepage "Best Selling" / "New & Upcoming" sections and
  // their "View All" pages — lower shows first. Every product participates
  // (unlike tags, there's no separate opt-in): null means unranked, and
  // unranked products fill in after the ranked ones, newest first. Two
  // separate columns (not one shared order, and not reusing tags) because a
  // product's position in one has nothing to do with the other.
  bestSellingRank: integer('best_selling_rank'),
  newAndUpcomingRank: integer('new_and_upcoming_rank'),
  // Absolute opt-out of the "unranked products fill in after the curated
  // ones" behavior above — e.g. a preorder that isn't shippable yet
  // shouldn't show up as Best Selling filler just because it's newest.
  // Independent of comingSoon/preorder (admin decides per product, not an
  // automatic rule) and wins over everything else: a hidden product never
  // shows in that section, curated or not.
  hideFromBestSelling: boolean('hide_from_best_selling').notNull().default(false),
  hideFromNewAndUpcoming: boolean('hide_from_new_and_upcoming').notNull().default(false),
  // Per-product description shown on its detail page. Falls back to a
  // generic trust-building paragraph on the frontend when empty — not
  // every product needs custom copy written before it can go live.
  description: text('description'),
  preorder: boolean('preorder').notNull().default(false),
  // In stock and purchasable now, unlike preorder — but physical fulfillment
  // is temporarily delayed (e.g. stock is in transit to us), so an order
  // containing it ships as one shipment once it arrives rather than
  // splitting. Doesn't block mixing with other items the way preorder does
  // (see hasMixedPreorderCart) — it's a warning, not a hard rule, and is
  // meant to be a short-lived admin toggle, not a permanent product trait.
  shipsWithDelay: boolean('ships_with_delay').notNull().default(false),
  // Listed and visible in the shop, but not yet purchasable — no price
  // shown, cart/checkout refuses it server-side too (see placeOrder), not
  // just a disabled button client-side. Distinct from `preorder` (which IS
  // purchasable now, for future shipment) and from `published` (which hides
  // it from the shop entirely).
  comingSoon: boolean('coming_soon').notNull().default(false),
  // Lets a product be linked to Square and fully set up while still hidden
  // from the public shop, e.g. staging a listing before its street date.
  published: boolean('published').notNull().default(true),
  placeholder: text('placeholder'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
})

export const users = pgTable('users', {
  id: uuid('id').primaryKey().defaultRandom(),
  email: text('email').notNull().unique(),
  passwordHash: text('password_hash'),
  googleId: text('google_id').unique(),
  name: text('name'),
  lastLoginAt: timestamp('last_login_at', { withTimezone: true }),
  // Null until verified. New password signups must verify via emailed code
  // before they can log in; Google signups are stamped verified immediately
  // (Google's own email_verified claim already proves ownership) — see
  // google-auth.ts / customers.ts. No default here deliberately — existing
  // rows are backfilled once in the migration, new rows start unverified.
  emailVerifiedAt: timestamp('email_verified_at', { withTimezone: true }),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
})

// One pending code per user — userId as the primary key means a resend just
