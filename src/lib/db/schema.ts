// General marketing list (new drops, restocks) — separate from customer
// accounts (users) since a subscriber never needs to log in. Fed by the
// homepage signup form, the checkout opt-in checkbox, and admin actions.
// Holds only *current* state (email unique) — unsubscribedAt null means
// currently subscribed, set means they left. subscribedAt is the most
// recent (re)subscribe time; createdAt is when this email first ever
// subscribed. Full subscribe/unsubscribe/resubscribe history lives in
// subscriberEvents below, same split as orders/orderStatusEvents.
export const subscribers = pgTable('subscribers', {
  id: uuid('id').primaryKey().defaultRandom(),
  email: text('email').notNull().unique(),
  // Only ever populated from checkout (the homepage form doesn't ask for
  // one) — lets emails greet someone by name instead of a blank.
  firstName: text('first_name'),
  source: text('source').notNull(), // source of the most recent (re)subscribe: 'homepage' | 'checkout' | 'admin'
  subscribedAt: timestamp('subscribed_at', { withTimezone: true }).notNull().defaultNow(),
  unsubscribedAt: timestamp('unsubscribed_at', { withTimezone: true }),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
})

// Append-only log of every subscribe/unsubscribe transition — this is what
// answers "did this email leave and come back, and when," not just the
// current state in subscribers above.
export const subscriberEvents = pgTable('subscriber_events', {
  id: uuid('id').primaryKey().defaultRandom(),
  email: text('email').notNull(),
  type: text('type').notNull(), // 'subscribed' | 'unsubscribed'
  source: text('source'), // set for 'subscribed' events only ('homepage' | 'checkout' | 'admin')
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
})

// Fast, atomically-updated current balance — same pattern as products.stock
// (guarded UPDATE ... WHERE balance >= amount prevents a double-spend race,
// see server/store-credit.ts's redeemStoreCredit). storeCreditEvents below
// is the append-only audit trail, same relationship as products.stock has
// to productEditEvents. One row per user, created on first issue.
export const storeCreditBalances = pgTable('store_credit_balances', {
  userId: uuid('user_id')
    .primaryKey()
    .references(() => users.id, { onDelete: 'cascade' }),
  balance: numeric('balance', { precision: 10, scale: 2, mode: 'number' }).notNull().default(0),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
})

// Every dollar issued or spent, permanently — balance above is derivable
// from summing these, but kept as a separate fast-path column rather than
// recomputed by aggregate on every read (see the comment there). amount is
// signed: positive for issued/reversed, negative for redeemed/adjusted-down.
export const storeCreditEvents = pgTable('store_credit_events', {
  id: uuid('id').primaryKey().defaultRandom(),
  userId: uuid('user_id')
    .notNull()
    .references(() => users.id, { onDelete: 'cascade' }),
  type: text('type').notNull(), // issued | redeemed | reversed | adjusted
  amount: numeric('amount', { precision: 10, scale: 2, mode: 'number' }).notNull(),
  // Set on 'redeemed' (which order spent it) and 'reversed' (which refund
  // gave it back) — null for an admin-issued grant or a manual correction.
  orderId: uuid('order_id').references(() => orders.id, { onDelete: 'set null' }),
  // Standard category from the admin dropdown (see lib/store-credit.ts) —
  // shown to admin in full, reduced to a generic attribution for the
  // customer (see getStoreCreditHistory in server/store-credit.ts).
  reason: text('reason'),
  // Free-text detail for admin's own bookkeeping — e.g. "combined orders
  // #EBI-102 and #EBI-104 into one shipment, refunding the difference as
  // credit." Admin-only, always: never included in the customer-facing
  // history query, unlike reason above (which is filtered per-request).
  note: text('note'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
})
